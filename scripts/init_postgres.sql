  current_jobs int NOT NULL DEFAULT 0,
  jobs_in_progress text DEFAULT NULL,
  version varchar(100) DEFAULT NULL,
  pod_created_at timestamptz(3) DEFAULT NULL,
  pod_started_at timestamptz(3) DEFAULT NULL,
  pod_ready_at timestamptz(3) DEFAULT NULL,
  cold_start_duration_ms bigint DEFAULT NULL,
  last_heartbeat timestamptz(3) NOT NULL,
  last_task_time timestamptz(3) DEFAULT NULL,
  total_tasks_completed bigint NOT NULL DEFAULT 0,
  total_tasks_failed bigint NOT NULL DEFAULT 0,
  total_execution_time_ms bigint NOT NULL DEFAULT 0,
  runtime_state jsonb DEFAULT NULL,
  failure_type varchar(32) DEFAULT NULL,
  failure_reason varchar(512) DEFAULT NULL,
  failure_details text DEFAULT NULL,
  failure_occurred_at timestamptz(3) DEFAULT NULL,
  pending_phase varchar(32) DEFAULT NULL,
  pending_phase_since timestamptz(3) DEFAULT NULL,
  pending_reason varchar(255) DEFAULT NULL,
  pending_message text DEFAULT NULL,
  spot_price numeric(10,6) DEFAULT NULL,
  spot_instance_type varchar(64) DEFAULT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_worker_id_unique ON workers (worker_id);
CREATE INDEX IF NOT EXISTS idx_workers_endpoint ON workers (endpoint);
CREATE INDEX IF NOT EXISTS idx_workers_status ON workers (status);
CREATE INDEX IF NOT EXISTS idx_workers_last_heartbeat ON workers (last_heartbeat);
CREATE INDEX IF NOT EXISTS idx_workers_failure_type ON workers (failure_type);
CREATE INDEX IF NOT EXISTS idx_workers_pending_phase ON workers (pending_phase);

