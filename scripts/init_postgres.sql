  gpu_count int NOT NULL DEFAULT 1,
  task_timeout int NOT NULL DEFAULT 0,
  env jsonb DEFAULT NULL,
  labels jsonb DEFAULT NULL,
  status varchar(50) NOT NULL DEFAULT 'active',
  enable_ptrace boolean NOT NULL DEFAULT false,
  max_pending_tasks int NOT NULL DEFAULT 1,
  runtime_state jsonb DEFAULT NULL,
  health_status varchar(16) DEFAULT 'HEALTHY',
  health_message varchar(512) DEFAULT NULL,
  last_health_check_at timestamptz(3) DEFAULT NULL,
  status_summary jsonb DEFAULT NULL,
  last_status_summary_at timestamptz(3) DEFAULT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_endpoint_unique ON endpoints (endpoint);
CREATE INDEX IF NOT EXISTS idx_endpoints_status ON endpoints (status);
CREATE INDEX IF NOT EXISTS idx_endpoints_created_at ON endpoints (created_at);
CREATE INDEX IF NOT EXISTS idx_endpoints_health_status ON endpoints (health_status);

