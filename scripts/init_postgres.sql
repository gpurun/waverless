-- Resource Specifications
CREATE TABLE IF NOT EXISTS resource_specs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  display_name varchar(255) NOT NULL,
  category varchar(50) NOT NULL,
  cpu varchar(50) DEFAULT NULL,
  memory varchar(50) NOT NULL,
  gpu varchar(50) DEFAULT NULL,
  gpu_type varchar(100) DEFAULT NULL,
  ephemeral_storage varchar(50) NOT NULL,
  shm_size varchar(50) DEFAULT NULL,
  resource_type varchar(20) NOT NULL DEFAULT 'serverless',
  platforms jsonb DEFAULT NULL,
  status varchar(50) NOT NULL DEFAULT 'active',
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
-- Seed the base resource catalog, matching the entries historically included
-- in MySQL initialization. Provider-specific specs remain configurable.
CREATE UNIQUE INDEX IF NOT EXISTS idx_spec_name_unique ON resource_specs (name);
CREATE INDEX IF NOT EXISTS idx_resource_specs_category ON resource_specs (category);
CREATE INDEX IF NOT EXISTS idx_resource_specs_status ON resource_specs (status);
CREATE INDEX IF NOT EXISTS idx_resource_specs_created_at ON resource_specs (created_at);

