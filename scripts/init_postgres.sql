-- Spec Capacity Status
CREATE TABLE IF NOT EXISTS spec_capacity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spec_name varchar(100) NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'limited', 'sold_out')),
  reason varchar(255) DEFAULT NULL,
  running_count int NOT NULL DEFAULT 0,
  pending_count int NOT NULL DEFAULT 0,
  failure_count int NOT NULL DEFAULT 0,
  spot_score int DEFAULT NULL,
  spot_price numeric(10,6) DEFAULT NULL,
  instance_type varchar(50) DEFAULT NULL,
  last_success_at timestamptz(3) DEFAULT NULL,
  last_failure_at timestamptz(3) DEFAULT NULL,
  last_spot_check_at timestamptz(3) DEFAULT NULL,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_spec_capacity_spec_name ON spec_capacity (spec_name);

-- Endpoints
CREATE TABLE IF NOT EXISTS endpoints (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint varchar(255) NOT NULL,
  spec_name varchar(100) NOT NULL,
  image varchar(500) NOT NULL,
  image_prefix varchar(500) NOT NULL DEFAULT '',
  image_digest varchar(255) NOT NULL DEFAULT '',
