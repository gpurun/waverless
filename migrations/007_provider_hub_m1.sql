-- ProviderHub M1: endpoint placement fields, provider slices, offers, image bindings.

ALTER TABLE endpoints ADD COLUMN IF NOT EXISTS gpu_type varchar(64) NOT NULL DEFAULT '';
ALTER TABLE endpoints ADD COLUMN IF NOT EXISTS placement_mode varchar(32) NOT NULL DEFAULT 'auto';
ALTER TABLE endpoints ADD COLUMN IF NOT EXISTS billing_mode varchar(32) NOT NULL DEFAULT 'on_demand';
ALTER TABLE endpoints ADD COLUMN IF NOT EXISTS logical_image varchar(512) NOT NULL DEFAULT '';
ALTER TABLE endpoints ADD COLUMN IF NOT EXISTS region_allowlist jsonb NOT NULL DEFAULT '[]'::jsonb;
ALTER TABLE endpoints ADD COLUMN IF NOT EXISTS active_slice_id bigint DEFAULT NULL;

CREATE TABLE IF NOT EXISTS endpoint_provider_slices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint varchar(255) NOT NULL,
  provider_id varchar(32) NOT NULL,
  provider_ref varchar(255) NOT NULL DEFAULT '',
  provider_sku_id varchar(128) NOT NULL DEFAULT '',
  physical_region varchar(128) NOT NULL DEFAULT '',
  logical_az_id varchar(64) NOT NULL DEFAULT '',
  desired_replicas integer NOT NULL DEFAULT 0,
  ready_replicas integer NOT NULL DEFAULT 0,
  status varchar(32) NOT NULL DEFAULT 'active',
  unit_cost_snapshot numeric(15, 4) DEFAULT NULL,
  currency varchar(8) NOT NULL DEFAULT 'USD',
  image_binding_id bigint DEFAULT NULL,
  resource_mark text NOT NULL DEFAULT '',
  last_scale_at timestamptz(3) DEFAULT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE INDEX IF NOT EXISTS idx_endpoint_provider_slices_endpoint
  ON endpoint_provider_slices (endpoint);
CREATE UNIQUE INDEX IF NOT EXISTS uq_endpoint_provider_slices_one_active
  ON endpoint_provider_slices (endpoint) WHERE status = 'active';

CREATE TABLE IF NOT EXISTS image_bindings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  digest varchar(255) NOT NULL,
  provider_id varchar(32) NOT NULL,
  physical_region varchar(128) NOT NULL,
  vendor_ref text NOT NULL DEFAULT '',
  ready boolean NOT NULL DEFAULT false,
  materialize_state varchar(32) NOT NULL DEFAULT 'none',
  open_cost_estimate numeric(15, 4) DEFAULT NULL,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT uq_image_bindings_key UNIQUE (digest, provider_id, physical_region)
);

CREATE TABLE IF NOT EXISTS provider_offers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id varchar(32) NOT NULL,
  sku_id varchar(128) NOT NULL,
  gpu_type varchar(64) NOT NULL,
  gpu_count integer NOT NULL,
  region varchar(128) NOT NULL DEFAULT '',
  logical_az_id varchar(64) NOT NULL DEFAULT '',
  billing_mode varchar(32) NOT NULL DEFAULT 'on_demand',
  unit_price numeric(15, 4) NOT NULL DEFAULT 0,
  currency varchar(8) NOT NULL DEFAULT 'USD',
  available_cap integer NOT NULL DEFAULT 0,
  resource_mark text NOT NULL DEFAULT '',
  synced_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT uq_provider_offers_row UNIQUE (provider_id, sku_id, gpu_count, region, billing_mode)
);
CREATE INDEX IF NOT EXISTS idx_provider_offers_placement
  ON provider_offers (gpu_type, gpu_count, billing_mode, provider_id);

ALTER TABLE workers ADD COLUMN IF NOT EXISTS provider_id varchar(32) NOT NULL DEFAULT '';
ALTER TABLE workers ADD COLUMN IF NOT EXISTS slice_id bigint DEFAULT NULL;
