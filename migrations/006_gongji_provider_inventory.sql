-- Gongji logical AZ registry + versioned inventory snapshots (PostgreSQL).

CREATE TABLE IF NOT EXISTS provider_region_registry_meta (
  provider_id varchar(32) NOT NULL PRIMARY KEY,
  registry_version bigint NOT NULL DEFAULT 1,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);

CREATE TABLE IF NOT EXISTS provider_region_bindings (
  logical_az_id varchar(64) NOT NULL PRIMARY KEY,
  display_name varchar(255) NOT NULL,
  compliance_domain varchar(32) NOT NULL,
  availability varchar(32) NOT NULL DEFAULT 'schedulable',
  maintenance_reason text DEFAULT NULL,
  provider_id varchar(32) NOT NULL DEFAULT 'gongji',
  physical_region_id varchar(128) NOT NULL,
  provider_sku_id varchar(128) NOT NULL,
  gpu_count integer NOT NULL,
  registry_version bigint NOT NULL DEFAULT 1,
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
);
CREATE INDEX IF NOT EXISTS idx_provider_region_bindings_provider
  ON provider_region_bindings (provider_id, physical_region_id, provider_sku_id);

CREATE TABLE IF NOT EXISTS provider_inventory_pulls (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id varchar(32) NOT NULL DEFAULT 'gongji',
  version bigint NOT NULL,
  status varchar(16) NOT NULL,
  error_message text DEFAULT NULL,
  observed_at timestamptz(3) NOT NULL,
  fresh_until timestamptz(3) DEFAULT NULL,
  device_count integer NOT NULL DEFAULT 0,
  offer_count integer NOT NULL DEFAULT 0,
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT uq_provider_inventory_pull_version UNIQUE (provider_id, version)
);
CREATE INDEX IF NOT EXISTS idx_provider_inventory_pulls_observed
  ON provider_inventory_pulls (provider_id, observed_at DESC);

CREATE TABLE IF NOT EXISTS provider_inventory_offers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pull_id bigint NOT NULL REFERENCES provider_inventory_pulls (id) ON DELETE CASCADE,
  pull_version bigint NOT NULL,
  provider_id varchar(32) NOT NULL DEFAULT 'gongji',
  physical_region_id varchar(128) NOT NULL,
  region_name varchar(255) NOT NULL DEFAULT '',
  gpu_name varchar(128) NOT NULL,
  gpu_count integer NOT NULL,
  device_name varchar(255) NOT NULL DEFAULT '',
  resource_mark text NOT NULL,
  inventory integer NOT NULL DEFAULT 0,
  price integer DEFAULT NULL,
  discount_price integer DEFAULT NULL,
  gpu_memory integer NOT NULL DEFAULT 0,
  memory integer NOT NULL DEFAULT 0,
  cpu_cores integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_provider_inventory_offers_pull
  ON provider_inventory_offers (pull_id);
CREATE INDEX IF NOT EXISTS idx_provider_inventory_offers_version_region
  ON provider_inventory_offers (provider_id, pull_version, physical_region_id, gpu_name, gpu_count);
